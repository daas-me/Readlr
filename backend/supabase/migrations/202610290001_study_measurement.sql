-- Pilot-study measurement for the proposal's SMART targets (four-week intervention).
-- Study days and weeks use the Philippine calendar (Asia/Manila).

create table if not exists public.study_settings (
  id smallint primary key default 1 check (id = 1),
  start_date date,
  updated_at timestamptz not null default now()
);
insert into public.study_settings (id) values (1) on conflict (id) do nothing;

-- Windows when the team runs required, teacher-scheduled use. Sessions outside them count as voluntary.
create table if not exists public.study_class_sessions (
  id bigint generated by default as identity primary key,
  started_at timestamptz not null default now(),
  ended_at timestamptz,
  started_by bigint references public.users(id) on delete set null,
  check (ended_at is null or ended_at >= started_at)
);
create unique index if not exists study_class_sessions_one_open on public.study_class_sessions ((true)) where ended_at is null;

-- App-use sessions, built from the 15-second presence heartbeat; a 5-minute gap starts a new session.
create table if not exists public.study_sessions (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  started_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  check (last_seen_at >= started_at)
);
create index if not exists study_sessions_user_idx on public.study_sessions (user_id, last_seen_at desc);

create table if not exists public.study_events (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  event_type text not null check (event_type in ('speech_attempt', 'stop_complete', 'daily_goal_shown')),
  book_id text check (book_id is null or char_length(book_id) between 1 and 40),
  stop_id text check (stop_id is null or char_length(stop_id) between 1 and 80),
  target text check (target is null or char_length(target) between 1 and 40),
  activity text check (activity is null or activity in ('practice', 'checkpoint', 'checkpoint_retry')),
  result text check (result is null or result in ('matched', 'different', 'uncertain', 'unavailable')),
  attempt_number smallint check (attempt_number is null or attempt_number between 1 and 100),
  latency_ms integer check (latency_ms is null or latency_ms between 0 and 600000),
  study_day date not null default ((now() at time zone 'Asia/Manila')::date),
  occurred_at timestamptz not null default now()
);
create index if not exists study_events_user_idx on public.study_events (user_id, occurred_at);
create unique index if not exists study_events_daily_goal_once on public.study_events (user_id, study_day) where event_type = 'daily_goal_shown';
create unique index if not exists study_events_stop_once on public.study_events (user_id, stop_id) where event_type = 'stop_complete';

alter table public.study_settings enable row level security;
alter table public.study_class_sessions enable row level security;
alter table public.study_sessions enable row level security;
alter table public.study_events enable row level security;
revoke all on public.study_settings, public.study_class_sessions, public.study_sessions, public.study_events from anon, authenticated;
grant all on public.study_settings, public.study_class_sessions, public.study_sessions, public.study_events to service_role;

create or replace function public.record_study_presence(p_user bigint)
returns void language plpgsql security definer set search_path = public as $$
declare current_id bigint;
begin
  perform pg_advisory_xact_lock(hashtext('study_presence'), p_user::integer);
  select id into current_id from study_sessions
    where user_id = p_user and last_seen_at > now() - interval '5 minutes'
    order by last_seen_at desc limit 1 for update;
  if found then
    update study_sessions set last_seen_at = now() where id = current_id;
  else
    insert into study_sessions (user_id) values (p_user);
  end if;
end $$;

-- Attempt number restarts after a matched word or 30 minutes without trying that word.
create or replace function public.record_speech_attempt(
  p_user bigint, p_target text, p_book text, p_activity text, p_result text, p_latency integer
) returns smallint language plpgsql security definer set search_path = public as $$
declare previous study_events; next_number smallint;
begin
  perform pg_advisory_xact_lock(hashtext('study_speech'), p_user::integer);
  select * into previous from study_events
    where user_id = p_user and event_type = 'speech_attempt' and target = p_target and occurred_at > now() - interval '30 minutes'
    order by occurred_at desc, id desc limit 1;
  next_number := case when not found or previous.result = 'matched' then 1 else least(previous.attempt_number + 1, 100) end;
  insert into study_events (user_id, event_type, target, book_id, activity, result, attempt_number, latency_ms)
    values (p_user, 'speech_attempt', p_target, p_book, p_activity, p_result, next_number, p_latency);
  return next_number;
end $$;

revoke all on function public.record_study_presence(bigint) from public, anon, authenticated;
revoke all on function public.record_speech_attempt(bigint, text, text, text, text, integer) from public, anon, authenticated;
grant execute on function public.record_study_presence(bigint) to service_role;
grant execute on function public.record_speech_attempt(bigint, text, text, text, text, integer) to service_role;
