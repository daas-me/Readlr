-- Additive Readlr 2.0 attempt evidence. This does not migrate legacy completion or practice data.
create table if not exists public.curriculum_releases (
  curriculum_version text not null check (char_length(curriculum_version) between 1 and 80),
  media_manifest_version text not null check (char_length(media_manifest_version) between 1 and 80),
  status text not null check (status in ('approved','revoked')),
  curriculum_sha256 char(64) not null check (curriculum_sha256 ~ '^[0-9a-f]{64}$'),
  manifest_sha256 char(64) not null check (manifest_sha256 ~ '^[0-9a-f]{64}$'),
  approved_by text not null check (char_length(approved_by) between 1 and 120),
  approval_reference text not null check (char_length(approval_reference) between 1 and 240),
  approved_at timestamptz not null,
  created_at timestamptz not null default now(),
  primary key (curriculum_version, media_manifest_version)
);

create table if not exists public.curriculum_attempts (
  id bigint generated by default as identity primary key,
  learner_id bigint not null references public.learner_profiles(id) on delete cascade,
  client_attempt_id uuid not null,
  session_id uuid not null,
  schema_version smallint not null default 1 check (schema_version = 1),
  curriculum_version text not null check (char_length(curriculum_version) between 1 and 80),
  media_manifest_version text not null check (char_length(media_manifest_version) between 1 and 80),
  activity_id text not null check (char_length(activity_id) between 1 and 80),
  skill_id text not null check (char_length(skill_id) between 1 and 80),
  content_id text not null check (char_length(content_id) between 1 and 80),
  activity_mode text not null check (activity_mode in ('teaching','practice','guided','adventure','independent_check','delayed_review')),
  response_type text not null check (response_type in ('selection','construction','speech_prediction','nonvoice','none')),
  response_value text check (response_value is null or (char_length(response_value) between 1 and 64 and response_value !~ '[\r\n]')),
  result text not null check (result in ('correct','incorrect','unclear','unavailable','no_response')),
  evidence_class text not null check (evidence_class in ('not_assessed','practiced','completed_with_help','independent_candidate')),
  hint_count smallint not null default 0 check (hint_count between 0 and 20),
  model_exposed boolean not null default false,
  answer_exposed boolean not null default false,
  reduced_choices boolean not null default false,
  media_asset_ids text[] not null default '{}',
  started_at timestamptz not null,
  completed_at timestamptz not null,
  captured_offline boolean not null default false,
  payload_hash char(64) not null check (payload_hash ~ '^[0-9a-f]{64}$'),
  received_at timestamptz not null default now(),
  unique (learner_id, client_attempt_id),
  foreign key (curriculum_version, media_manifest_version)
    references public.curriculum_releases(curriculum_version, media_manifest_version),
  check (completed_at >= started_at),
  check (cardinality(media_asset_ids) <= 20)
);

create index if not exists curriculum_attempts_learner_cursor_idx
  on public.curriculum_attempts(learner_id, id);
create index if not exists curriculum_attempts_learner_skill_idx
  on public.curriculum_attempts(learner_id, curriculum_version, skill_id, completed_at desc);

comment on table public.curriculum_attempts is
  'Append-only item evidence. Adventure completion and legacy practice remain separate; no raw child audio is stored.';
comment on table public.curriculum_releases is
  'Server allowlist for educator-approved immutable curriculum and media pairs. Provisional drafts are not inserted.';
comment on column public.curriculum_attempts.evidence_class is
  'Attempt context only. independent_candidate is not learner mastery until an approved aggregation rule evaluates it.';

